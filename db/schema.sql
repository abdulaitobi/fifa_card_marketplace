CREATE TABLE IF NOT EXISTS players (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  playername varchar(255) NOT NULL CHECK (length(btrim(playername)) > 0),
  countryname varchar(255) NOT NULL CHECK (countryname ~ '^[A-Z]{2}$'),
  price numeric NOT NULL CHECK (price >= 0 AND price <= 999999999999.99 AND price = round(price, 2))
);
